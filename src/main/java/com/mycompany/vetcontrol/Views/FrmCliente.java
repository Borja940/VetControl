    private void cargarClientesTabla() {
    try {
        // Obtener la lista completa de clientes desde tu DAO
     
        List<ClienteModel> lista = dao.listar(); 
        
         DefaultTableModel modelo = (DefaultTableModel) TblClientes.getModel();
        // Obtener el modelo de tabla
        modelo.setRowCount(0); 
        
        // Llenar la tabla fila por fila 
        for (ClienteModel c : lista) {
            Object[] rowData = {      
                c.getIdCliente(),   
                c.getNombre(),      
                c.getDireccion(),   
                c.getTelefono(),    
                c.getCorreo()       
            };
            modelo.addRow(rowData);
        }
          TblClientes.setModel(modelo);
             
             // anchos de la tabla
             TblClientes.getColumnModel().getColumn(0).setPreferredWidth(50);
             TblClientes.getColumnModel().getColumn(1).setPreferredWidth(80);
             TblClientes.getColumnModel().getColumn(2).setPreferredWidth(80);
             TblClientes.getColumnModel().getColumn(3).setPreferredWidth(80);
             TblClientes.getColumnModel().getColumn(4).setPreferredWidth(80);
             TblClientes.getColumnModel().getColumn(5).setPreferredWidth(80);
         
    } catch (Exception ex) {
        System.getLogger(FrmCliente.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
    }
}
       
