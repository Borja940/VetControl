    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
          try {
        //leer datos del formulario
        String nombre= txtNombre.getText().trim();
        String direccion = txtDireccion.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();
     
        // Validar
        if(nombre.isBlank()){
            
            JOptionPane.showMessageDialog(this,"El nombre es obligatorio");
            return;
        }
        if(direccion.isBlank()){
            JOptionPane.showMessageDialog(this,"Ingrese un correo electrónico");
            return;
        }
        if(telefono.isBlank()){
            JOptionPane.showMessageDialog(this,"El número de telefono es obligatorio");
            return;
        }
        if(correo.isBlank()){
            JOptionPane.showMessageDialog(this,"La dirección de correo electrinico es obligatorio");
            return;
            
            
        }
        // armar el modelo y llamar a DAO
        ClienteModel cliente = new ClienteModel(nombre, direccion, telefono, correo);
        dao.insertar (cliente);
        
         
        // notificar usuario
        JOptionPane.showMessageDialog(this,"Registrado con éxito");
        
        cargarClientesTabla();
       
        txtNombre.setText("");
        txtCorreo.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
        } catch (Exception ex) {
          JOptionPane.showMessageDialog(this,ex.getMessage());
        }   
    
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
        int filaSeleccionada = TblClientes.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente en la tabla");
        return;
    }
        
        try {
        //  Obtener el ID real del cliente 
        int idCliente = Integer.parseInt(TblClientes.getValueAt(filaSeleccionada, 0).toString());
        
        // Borrarlo en la base de datos
        dao.eliminar(idCliente);
        
        JOptionPane.showMessageDialog(this, "Cliente eliminado con éxito");
        
        // cargar la tabla para que desaparezca visualmente
        cargarClientesTabla(); 
        
    } catch (Exception ex) {
        System.getLogger(FrmCliente.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
    }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

